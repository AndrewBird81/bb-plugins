// Bundles the guest page (guest/main.tsx) into src/guest-bundle.generated.ts,
// which the host worker serves. Run `npm run build:guest` after editing guest/.
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [join(root, "guest/main.tsx")],
  bundle: true,
  minify: true,
  format: "esm",
  target: "es2022",
  platform: "browser",
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  write: false,
});
const code = result.outputFiles[0].text;
await writeFile(
  join(root, "src/guest-bundle.generated.ts"),
  `// Generated by scripts/build-guest.mjs from guest/main.tsx. Do not edit.\nexport const GUEST_JS = ${JSON.stringify(code)};\n`,
);
console.log(`guest bundle: ${(code.length / 1024).toFixed(0)} KiB`);
